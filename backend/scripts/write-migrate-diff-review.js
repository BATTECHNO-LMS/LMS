require('dotenv').config();
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const outPath = path.join(__dirname, '..', '..', 'docs', 'maintenance', '_migrate_diff_live_to_schema.sql');
const prismaCli = path.join(__dirname, '..', 'node_modules', 'prisma', 'build', 'index.js');

const result = spawnSync(
  process.execPath,
  [
    prismaCli,
    'migrate',
    'diff',
    '--from-schema-datasource',
    'prisma/schema.prisma',
    '--to-schema-datamodel',
    'prisma/schema.prisma',
    '--script',
  ],
  {
    encoding: 'utf8',
    cwd: path.join(__dirname, '..'),
    env: process.env,
    windowsHide: true,
  }
);

fs.writeFileSync(
  outPath,
  [
    '-- REVIEW ONLY — do not execute automatically.',
    '-- Generated by scripts/write-migrate-diff-review.js',
    `-- exit_code=${result.status}`,
    '-- Compare: live DB (schema datasource) → current schema.prisma',
    '',
    result.stdout || '-- (empty stdout: no SQL changes required to match schema.prisma)',
    '',
    result.stderr ? `-- stderr:\n-- ${String(result.stderr).split('\n').join('\n-- ')}` : '',
  ].join('\n')
);

console.log('wrote', outPath);
console.log('exit', result.status);
console.log((result.stdout || '').slice(0, 1500) || '(empty stdout = no SQL drift vs schema.prisma)');
if (result.error) console.error(result.error);
if (result.status !== 0 && result.status !== 2) process.exitCode = result.status || 1;
