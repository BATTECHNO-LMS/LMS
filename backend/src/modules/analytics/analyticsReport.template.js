function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function fmtNum(value, suffix = '') {
  if (value === null || value === undefined || value === '') return '—';
  return `${value}${suffix}`;
}

function fmtDate(value, lang) {
  if (!value) return '—';
  const d = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(d.getTime())) return '—';
  return d.toLocaleString(lang === 'en' ? 'en-GB' : 'ar-JO', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}

function fmtRange(filters, copy) {
  if (filters.from && filters.to) {
    const from = filters.from instanceof Date ? filters.from.toISOString().slice(0, 10) : String(filters.from).slice(0, 10);
    const to = filters.to instanceof Date ? filters.to.toISOString().slice(0, 10) : String(filters.to).slice(0, 10);
    return `${from} → ${to}`;
  }
  if (filters.from) {
    const from = filters.from instanceof Date ? filters.from.toISOString().slice(0, 10) : String(filters.from).slice(0, 10);
    return `${from} → ${copy.allTime}`;
  }
  return copy.allTime;
}

function kpiTone(key, value) {
  const n = Number(value);
  if (Number.isNaN(n)) return 'neutral';
  if (['missingEvidence', 'delayedAssessments', 'openQaIssues', 'openIntegrityCases', 'pendingEnrollments'].includes(key)) {
    if (n === 0) return 'good';
    if (n <= 5) return 'warn';
    return 'bad';
  }
  if (key === 'attendanceRatePct') {
    if (n >= 85) return 'good';
    if (n >= 70) return 'warn';
    return 'bad';
  }
  return 'neutral';
}

function buildRecommendations(ctx) {
  const { lang, overview, attendance, copy } = ctx;
  const kpis = overview.kpis || {};
  const recs = [];

  if ((kpis.missingEvidence || 0) > 0) {
    recs.push(
      lang === 'en'
        ? 'Review missing evidence files by university and cohort.'
        : 'يوصى بمراجعة ملفات الأدلة الناقصة حسب الجامعة والدفعة.'
    );
  }
  if ((kpis.delayedAssessments || 0) > 0) {
    recs.push(
      lang === 'en'
        ? 'Follow up on delayed assessments with instructors and academic admins.'
        : 'يوصى بمتابعة التقييمات المتأخرة مع المدربين.'
    );
  }
  if ((kpis.openIntegrityCases || 0) > 0) {
    recs.push(
      lang === 'en'
        ? 'Prioritize review of open integrity cases.'
        : 'يوصى بمراجعة حالات النزاهة المفتوحة ذات الأولوية.'
    );
  }
  if ((kpis.openQaIssues || 0) > 0) {
    recs.push(
      lang === 'en'
        ? 'Address open QA reviews and linked corrective actions.'
        : 'يوصى بمعالجة مراجعات الجودة المفتوحة وإجراءات التصحيح المرتبطة.'
    );
  }
  if ((kpis.pendingEnrollments || 0) > 0) {
    recs.push(
      lang === 'en'
        ? 'Process pending enrollment requests to reduce onboarding delays.'
        : 'يوصى بمعالجة طلبات التسجيل المعلّقة لتقليل تأخير الالتحاق.'
    );
  }
  const rate = Number(kpis.attendanceRatePct);
  if (!Number.isNaN(rate) && rate > 0 && rate < 75) {
    recs.push(
      lang === 'en'
        ? 'Analyze causes of low attendance in affected cohorts.'
        : 'يوصى بتحليل أسباب انخفاض الحضور في الدفعات المتأثرة.'
    );
  }
  if ((attendance?.lowAttendanceCohorts?.length || 0) > 0) {
    recs.push(
      lang === 'en'
        ? `Monitor ${attendance.lowAttendanceCohorts.length} cohort(s) flagged for low attendance.`
        : `يوصى بمراقبة ${attendance.lowAttendanceCohorts.length} دفعة ذات مؤشرات حضور منخفضة.`
    );
  }
  if ((kpis.recognitionReady || 0) > 0) {
    recs.push(
      lang === 'en'
        ? 'Advance recognition-ready requests toward submission.'
        : 'يوصى بإتمام تقديم طلبات الاعتراف الجاهزة.'
    );
  }

  if (!recs.length) {
    recs.push(
      lang === 'en'
        ? 'Indicators are within acceptable ranges for the selected scope. Continue routine monitoring.'
        : 'المؤشرات ضمن نطاق مقبول للفلاتر المحددة. يُنصح بمواصلة المتابعة الروتينية.'
    );
  }
  return recs;
}

function renderTable(headers, rows) {
  const head = headers.map((h) => `<th>${escapeHtml(h)}</th>`).join('');
  const body = rows.length
    ? rows.map((row) => `<tr>${row.map((c) => `<td>${escapeHtml(c)}</td>`).join('')}</tr>`).join('')
    : `<tr><td colspan="${headers.length}" class="empty">—</td></tr>`;
  return `<table class="data-table"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

function renderKpiCards(ctx) {
  const { lang, overview, copy } = ctx;
  const kpis = overview.kpis || {};
  return KPI_DEFS.map((def) => {
    const raw = kpis[def.key];
    const value = def.suffix ? `${raw ?? 0}${def.suffix}` : String(raw ?? 0);
    const tone = kpiTone(def.key, def.suffix ? String(raw).replace('%', '') : raw);
    const label = lang === 'en' ? def.en : def.ar;
    const helper = lang === 'en' ? def.helperEn : def.helperAr;
    const toneLabel = tone === 'good' ? copy.adequate : tone === 'bad' ? copy.critical : copy.attention;
    return `
      <div class="kpi-card tone-${tone}">
        <div class="kpi-card__label">${escapeHtml(label)}</div>
        <div class="kpi-card__value">${escapeHtml(value)}</div>
        <div class="kpi-card__helper">${escapeHtml(helper)}</div>
        <div class="kpi-card__badge">${escapeHtml(toneLabel)}</div>
      </div>
    `;
  }).join('');
}

